import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = resolve(projectRoot, 'assets/data/concerts.json');
const outputPath = resolve(projectRoot, 'assets/data/concerts.js');

const source = await readFile(inputPath, 'utf8');
const concerts = JSON.parse(source);

if (!Array.isArray(concerts)) {
  throw new TypeError('assets/data/concerts.json must contain an array');
}

const generated = `/**\n * Generated from assets/data/concerts.json.\n * Do not edit this file directly; run: node tools/build-concert-data.mjs\n */\nwindow.LIVIBE_CONCERT_DATA = ${JSON.stringify(concerts, null, 2)};\n`;

await writeFile(outputPath, generated, 'utf8');
console.log(`Generated ${concerts.length} concerts: ${outputPath}`);
