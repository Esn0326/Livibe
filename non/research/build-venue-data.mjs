import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const venuesPath = resolve(projectRoot, 'assets/data/venue-catalog.json');
const locationsPath = resolve(projectRoot, 'assets/data/locations.json');
const outputPath = resolve(projectRoot, 'assets/data/venues.js');

const [venuesSource, locationsSource] = await Promise.all([
  readFile(venuesPath, 'utf8'),
  readFile(locationsPath, 'utf8')
]);
const venues = JSON.parse(venuesSource);
const locations = JSON.parse(locationsSource);

if (!Array.isArray(venues)) {
  throw new TypeError('assets/data/venue-catalog.json must contain an array');
}
if (!locations || typeof locations !== 'object' || Array.isArray(locations)) {
  throw new TypeError('assets/data/locations.json must contain an object');
}

const generated = `/**
 * Generated from assets/data/venue-catalog.json and assets/data/locations.json.
 * Do not edit this file directly; run: node tools/build-venue-data.mjs
 */
window.LIVIBE_VENUE_DATA = ${JSON.stringify({ venues, locations }, null, 2)};
`;

await writeFile(outputPath, generated, 'utf8');
console.log(`Generated ${venues.length} venues and ${Object.keys(locations.cities ?? {}).length} cities: ${outputPath}`);
